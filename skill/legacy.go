// Legacy reports whether digest, the SHA-256 in hex of a file named file
// in a connect directory, is a version auu installed there: file is
// SKILL.md or reference.md, and anything else is not.
func Legacy(file, digest string) bool {
	var list []string
	switch file {
	case "SKILL.md":
		list = LegacyConnect
	case Reference:
		list = LegacyReference
	}
	for _, d := range list {
		if d == digest {
			return true
		}
	}
	return false
}
